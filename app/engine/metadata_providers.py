"""Gemini, Groq and Ollama callers that turn one image into Adobe-ready metadata.

All providers are optional runtime dependencies: import happens inside the
call so the app still starts (and the upscaler still works) without them.
Errors from the SDKs/HTTP layer are wrapped in ``ProviderError`` — the
original exception classes are never reconstructed.

Ollama is offered in two modes that share the same ``/api/chat`` shape:
``Ollama (Local)`` talks to a server on the user's machine (no credential, the
image never leaves the computer) and ``Ollama Cloud`` talks to Ollama's hosted
API at ``https://ollama.com`` with a Bearer API key (the image IS uploaded).
"""

from __future__ import annotations

import base64
import time
from urllib.parse import urlparse

from .metadata_settings import (
    MetadataSettings, ImageMetadata, ProviderError,
    build_prompt, parse_model_json, prepare_analysis_bytes,
    sanitize_keywords, ADOBE_KEYWORDS_MAX,
    DEFAULT_MODELS, MODEL_CATALOGUES, API_KEY_ENV_VARS,
    OLLAMA_LOCAL, OLLAMA_CLOUD, OLLAMA_LOCAL_URL, OLLAMA_CLOUD_URL,
    is_ollama, provider_requires_key,
)

# HTTP codes worth retrying with backoff. Everything else (401/403/404/400…)
# is a permanent problem — bad key, retired model, rejected image.
_TRANSIENT_CODES = {408, 409, 425, 429, 500, 502, 503, 504}
_TRANSIENT_HINTS = ("rate limit", "timed out", "timeout", "temporarily",
                    "unavailable", "overloaded", "connection", "reset by peer")

MAX_ATTEMPTS = 3
BACKOFF_BASE = 2.0  # seconds; doubles per attempt

# A local model can take a while to load on CPU; cloud requests are network-bound.
OLLAMA_LOCAL_TIMEOUT = 300
OLLAMA_CLOUD_TIMEOUT = 120
OLLAMA_LOOKUP_TIMEOUT = 15

# Missing keywords still tolerated with one follow-up request (see
# _top_up_keywords). Anything shorted by more than this is left as the model
# answered and can be regenerated by hand.
_KEYWORD_TOP_UP_MAX = 12


def _is_transient(exc: Exception) -> bool:
    # An explicit flag set by generate_metadata wins: the *final* wrapped
    # ProviderError's message ("… failed after N attempts: …") no longer
    # matches the hint list, and network-flavoured SDK exceptions often
    # carry no HTTP code — without the flag the worker would misclassify
    # an exhausted transient failure as permanent and skip retry passes.
    if getattr(exc, "retryable", None) is True:
        return True
    code = getattr(exc, "code", None)
    if isinstance(code, int):
        return code in _TRANSIENT_CODES
    msg = str(exc).lower()
    return any(h in msg for h in _TRANSIENT_HINTS) and "no longer available" not in msg


def is_retryable_error(exc: Exception) -> bool:
    """True when a later *batch-level* retry pass could plausibly succeed.

    Used by ``MetadataWorker`` to decide whether a failed image is worth an
    automatic retry (rate limits, timeouts, network blips, provider 5xx) or
    is a permanent problem that must be surfaced to the user immediately
    (bad API key, unreadable/unsupported image, retired model).
    """
    return _is_transient(exc)


def _retirement_hint(exc: Exception) -> str:
    """Google names the replacement model inside 404 retirement messages."""
    msg = str(exc)
    if "no longer available" in msg and "use models/" in msg:
        tail = msg.split("use models/")[-1].strip()
        replacement = tail.strip("\"'.,; ").split()[0]
        return f" Try switching the model to '{replacement}'."
    return ""


def missing_dependency(package: str) -> ProviderError:
    return ProviderError(
        f"The '{package}' package is not installed. Run: "
        f".venv\\Scripts\\python -m pip install {package}")


def _classify_http(provider: str, code: int | None, detail: str,
                   model: str = "") -> str:
    """Turn a raw HTTP failure into a distinguishable, actionable message."""
    if code in (401, 403):
        if provider == OLLAMA_CLOUD:
            return (f"{provider} rejected your API key (HTTP {code}) — create a "
                    f"key at https://ollama.com/settings/keys, then re-enter it "
                    "on the Metadata screen (or set OLLAMA_API_KEY).")
        return (f"{provider} rejected your API key (HTTP {code}) — check the "
                f"{provider} key on the Metadata screen.")
    if code == 402:
        return (f"{provider} refused to run this model without payment or "
                f"credits (HTTP 402) — check your plan/usage at "
                "https://ollama.com/settings, or pick a model your account "
                "includes.")
    if code == 404:
        return (f"{provider} has no model '{model}' (HTTP 404) — it is retired, "
                "not installed, or not part of this account's access; run the "
                "vision-model availability check and pick a listed model.")
    if code == 413:
        return (f"{provider} refused the image because it is too large "
                f"(HTTP 413) — pick a smaller source image: {detail}")
    if code == 429:
        return (f"{provider} rate limit reached (HTTP 429) — too many "
                "requests; waiting before trying again.")
    if code == 400:
        return (f"{provider} rejected the request (HTTP 400) — the image or "
                f"prompt was not accepted (a text-only model cannot take "
                f"images): {detail}")
    return f"{provider} API error ({code}): {detail}"


def _resolve_model(settings: MetadataSettings) -> str:
    """Model for the *currently selected* provider.

    One settings object carries every provider's choice, so a model ID that
    belongs to a different provider (or an empty one) falls back to this
    provider's own default instead of guaranteeing a 404. Any other name is
    passed through untouched — local Ollama users pick from the discovered
    list, and the editable combo still accepts custom/quantised tags.
    """
    own = MODEL_CATALOGUES.get(settings.provider, [])
    others = {m for models in MODEL_CATALOGUES.values()
              for m in models if m not in own}
    model = (settings.model or "").strip()
    if not model:
        return DEFAULT_MODELS[settings.provider]
    if model in others:
        # Local tags are the same families as the cloud IDs (`gemma4` vs
        # `gemma4:31b`), so a shared family name is a real local model —
        # quantised tags must not be swapped for the default.
        if settings.provider != OLLAMA_LOCAL:
            return DEFAULT_MODELS[settings.provider]
        if model.split(":", 1)[0] not in {m.split(":", 1)[0] for m in own}:
            return DEFAULT_MODELS[settings.provider]
    return model


def generate_metadata(image_path, settings: MetadataSettings, api_key: str,
                      log=None) -> ImageMetadata:
    """Generate metadata for one image with bounded retries.

    ``log`` is an optional callable for human-readable progress lines.
    Raises ``ProviderError`` when every attempt fails. Local Ollama needs no
    ``api_key`` — everything else does.
    """
    if provider_requires_key(settings.provider) and not api_key:
        env = API_KEY_ENV_VARS.get(settings.provider, "YOUR_API_KEY")
        raise ProviderError(
            f"No API key provided for {settings.provider}. Enter one, or set "
            f"the {env} environment variable.")
    # Raises ProviderError with a clear message for unreadable/unsupported images.
    data, mime = prepare_analysis_bytes(image_path)
    prompt = build_prompt(settings)

    last_error: Exception | None = None
    last_transient = False
    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            if settings.provider == "Gemini":
                text = _call_gemini(data, mime, prompt, settings, api_key)
            elif settings.provider == "Groq":
                text = _call_groq(data, mime, prompt, settings, api_key)
            elif is_ollama(settings.provider):
                text = _call_ollama(data, mime, prompt, settings, api_key)
            else:
                raise ProviderError(f"Unknown provider: {settings.provider}")
            meta = parse_model_json(text, settings)
            if is_ollama(settings.provider):
                meta = _top_up_keywords(meta, data, mime, settings, api_key, log)
            return meta
        except ProviderError as exc:
            last_error = exc
            last_transient = _is_transient(exc)
            if not last_transient:
                hint = _retirement_hint(exc)
                raise ProviderError(f"{exc}{hint}",
                                    code=getattr(exc, "code", None)) from exc
        except ValueError as exc:
            # The provider answered, just not in the JSON shape we asked for
            # (truncated reply, stray prose). Re-asking the same model normally
            # works, so this counts as a temporary failure for this image.
            last_error = exc
            last_transient = True
        except Exception as exc:  # unexpected SDK/transport failure
            last_error = exc
            raise ProviderError(f"{settings.provider} request failed: {exc}",
                                code=getattr(exc, "code", None)) from exc
        if attempt < MAX_ATTEMPTS:
            delay = BACKOFF_BASE * (2 ** (attempt - 1))
            if log:
                log(f"  {settings.provider} hiccup ({last_error}); retrying in "
                    f"{delay:.0f}s — attempt {attempt + 1}/{MAX_ATTEMPTS}")
            time.sleep(delay)
    # Per-request attempts exhausted on a TRANSIENT error: carry that fact on
    # the final ProviderError so MetadataWorker still runs batch retry passes.
    final = ProviderError(f"{settings.provider} failed after {MAX_ATTEMPTS} attempts: "
                          f"{last_error}", code=getattr(last_error, "code", None))
    final.retryable = True if last_transient else None
    raise final


# -- provider calls ------------------------------------------------------------
def _call_gemini(data: bytes, mime: str, prompt: str, settings: MetadataSettings,
                 api_key: str) -> str:
    try:
        from google import genai
        from google.genai import types
    except ImportError as exc:
        raise missing_dependency("google-genai") from exc

    client = genai.Client(api_key=api_key)
    model = _resolve_model(settings)
    try:
        response = client.models.generate_content(
            model=model,
            # Inline image bytes must go through Part.from_bytes with the real
            # MIME type. Passing a types.Image object in ``contents`` fails in
            # google-genai >= 2.x with "file uri and mime_type are required".
            contents=[prompt, types.Part.from_bytes(data=data, mime_type=mime)],
            config=types.GenerateContentConfig(temperature=0.4),
        )
    except Exception as exc:
        code = getattr(exc, "code", None)
        raise ProviderError(
            _classify_http("Gemini", code, f"{type(exc).__name__}: {exc}", model),
            code=code) from exc
    text = getattr(response, "text", None)
    if not text:
        raise ProviderError("Gemini returned an empty response.")
    return text


def _call_groq(data: bytes, mime: str, prompt: str, settings: MetadataSettings,
               api_key: str) -> str:
    """Groq exposes an OpenAI-compatible chat API — plain HTTPS, no SDK needed."""
    try:
        import requests
    except ImportError as exc:
        raise missing_dependency("requests") from exc

    model = _resolve_model(settings)
    image_b64 = base64.b64encode(data).decode("ascii")
    body = {
        "model": model,
        "temperature": 0.4,
        "max_tokens": 2048,
        "messages": [{
            "role": "user",
            "content": [
                {"type": "text", "text": prompt},
                {"type": "image_url",
                 "image_url": {"url": f"data:{mime};base64,{image_b64}"}},
            ],
        }],
    }
    try:
        resp = requests.post(
            "https://api.groq.com/openai/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}",
                     "Content-Type": "application/json"},
            json=body, timeout=120,
        )
    except requests.Timeout as exc:
        raise ProviderError(
            f"Groq request timed out after 120s — check your connection "
            f"and retry: {exc}") from exc
    except requests.ConnectionError as exc:
        raise ProviderError(
            f"Could not reach the Groq API — check your internet "
            f"connection: {exc}") from exc
    except requests.RequestException as exc:
        raise ProviderError(f"Groq request failed: {exc}") from exc
    if resp.status_code != 200:
        detail = _error_detail(resp)
        raise ProviderError(
            _classify_http("Groq", resp.status_code, detail or resp.reason, model),
            code=resp.status_code)
    try:
        return resp.json()["choices"][0]["message"]["content"]
    except (KeyError, IndexError, ValueError) as exc:
        raise ProviderError(f"Groq returned an unexpected response shape: {exc}") from exc


# -- Ollama: local server or Ollama's hosted cloud ------------------------------
def ollama_base(settings) -> str:
    """Normalised ``scheme://host[:port]`` for an Ollama mode.

    Cloud is pinned to Ollama's official API host. Local honours a custom
    address (Ollama as a service, a non-default port, another LAN machine) and
    rejects nonsense here instead of failing deep inside an HTTP call — an
    invalid address is a permanent settings error, never retried.
    """
    if isinstance(settings, MetadataSettings):
        raw = (OLLAMA_CLOUD_URL if settings.provider == OLLAMA_CLOUD
               else settings.ollama_url)
    else:
        raw = settings
    raw = (raw or "").strip() or OLLAMA_LOCAL_URL
    if "://" not in raw:
        raw = f"http://{raw}"
    parsed = urlparse(raw)
    host = parsed.netloc.strip()
    if (parsed.scheme not in ("http", "https") or not host
            or any(c.isspace() for c in host)):
        raise ProviderError(
            f"'{raw}' is not a valid Ollama server address — use the default "
            f"{OLLAMA_LOCAL_URL} (or http://192.168.0.5:11434 for a machine "
            "running Ollama).")
    return f"{parsed.scheme}://{host}"


def _ollama_headers(api_key: str) -> dict:
    """Local Ollama needs no auth header; the cloud API requires Bearer."""
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"
    return headers


def _error_detail(resp) -> str:
    """Best-effort provider error text from a failed HTTP response."""
    try:
        payload = resp.json()
        err = payload.get("error") if isinstance(payload, dict) else None
        if isinstance(err, dict):
            return str(err.get("message", ""))[:300]
        if err is not None:
            return str(err)[:300]
        return str(payload)[:300]
    except Exception:
        return str(getattr(resp, "text", "") or "")[:300]


def _ollama_chat(requests, base: str, body: dict, api_key: str, timeout: int,
                 local: bool, settings: MetadataSettings, model: str,
                 allow_400: bool = False):
    """POST one ``/api/chat`` request, mapping failures to ProviderError.

    ``allow_400`` returns the response instead of raising, so the caller can
    react to a rejected request field.
    """
    try:
        resp = requests.post(f"{base}/api/chat", headers=_ollama_headers(api_key),
                             json=body, timeout=timeout)
    except requests.Timeout as exc:
        where = ("the model may still be loading on this machine" if local
                 else "check your internet connection")
        raise ProviderError(
            f"{settings.provider} took over {timeout}s to answer — {where}; "
            f"trying again shortly: {exc}") from exc
    except requests.ConnectionError as exc:
        if local:
            # Nothing is listening / the app is stopped: retrying can't help,
            # so this message deliberately avoids transient wording.
            raise ProviderError(
                f"Ollama is not running on this computer ({base}) — start the "
                "Ollama app (or run 'ollama serve'), then press the "
                "vision-model check again.") from exc
        raise ProviderError(
            f"Could not reach Ollama Cloud ({base}) — check your internet "
            f"connection: {exc}") from exc
    except requests.RequestException as exc:
        raise ProviderError(
            f"{settings.provider} request failed: {exc}") from exc
    if resp.status_code != 200 and not (allow_400 and resp.status_code == 400):
        raise ProviderError(
            _classify_http(settings.provider, resp.status_code,
                           _error_detail(resp) or resp.reason, model),
            code=resp.status_code)
    return resp


def _call_ollama(data: bytes, mime: str, prompt: str, settings: MetadataSettings,
                 api_key: str) -> str:
    """One image → text through Ollama's official ``/api/chat`` endpoint.

    The REST API takes the image as a base64 string in the message's
    ``images`` array (docs.ollama.com/capabilities/vision); ``format: json``
    asks the server to constrain the reply to the JSON object our parser
    expects. Nothing is uploaded in local mode; cloud mode posts to
    ollama.com and the image travels with the request.

    ``think: false`` matters: on a reasoning model the hidden chain of thought
    otherwise eats the whole ``num_predict`` budget and the visible answer comes
    back empty (observed against a local qwen3.5 server).
    """
    try:
        import requests
    except ImportError as exc:
        raise missing_dependency("requests") from exc

    local = settings.provider == OLLAMA_LOCAL
    base = ollama_base(settings)
    model = _resolve_model(settings)
    timeout = OLLAMA_LOCAL_TIMEOUT if local else OLLAMA_CLOUD_TIMEOUT
    body = {
        "model": model,
        "messages": [{
            "role": "user",
            "content": prompt,
            "images": [base64.b64encode(data).decode("ascii")],
        }],
        "stream": False,
        "format": "json",
        "think": False,
        # A 50-keyword Adobe set plus a full description is a long answer; the
        # budget has to leave room for the closing brace or the JSON is cut off.
        "options": {"temperature": 0.4, "num_predict": 3072},
    }
    resp = _ollama_chat(requests, base, body, api_key, timeout, local, settings,
                        model, allow_400=True)
    if resp.status_code == 400 and "think" in _error_detail(resp).lower():
        # An older server that does not know the field: ask again without it.
        body = {k: v for k, v in body.items() if k != "think"}
        resp = _ollama_chat(requests, base, body, api_key, timeout, local,
                            settings, model)
    elif resp.status_code != 200:
        raise ProviderError(
            _classify_http(settings.provider, resp.status_code,
                           _error_detail(resp) or resp.reason, model),
            code=resp.status_code)
    try:
        text = resp.json()["message"]["content"]
    except (KeyError, IndexError, ValueError, TypeError) as exc:
        raise ProviderError(
            f"{settings.provider} returned an unexpected response shape: {exc}") from exc
    if not str(text or "").strip():
        raise ProviderError(
            f"{settings.provider} model '{model}' answered with no text — it "
            "refused the image or ran out of answer space. Use "
            "“Regenerate Selected”; if it repeats, run the vision-model check "
            "and pick a different image-capable model.")
    return str(text)


def _keyword_top_up_prompt(settings: MetadataSettings, existing: list[str],
                           missing: int) -> str:
    """Second, cheap request asking only for the keywords that are still out."""
    listed = ", ".join(existing) or "(none yet)"
    return (
        "You are completing Adobe Stock contributor keywords for the attached image.\n"
        f"Write all values in {settings.language}.\n"
        "Respond with ONLY a JSON object, no markdown fences, shaped "
        "{\"keywords\": [\"...\"]}\n"
        f"- keywords: exactly {missing} additional single words or short phrases "
        "that genuinely describe this image, most important first, without "
        f"repeating any of these already collected ones: {listed}\n"
        "No trademarks, no artist names.\n")


def _keywords_from_json(text: str) -> list[str]:
    """Keyword list from a top-up reply, tolerating prose around the JSON."""
    import json
    import re

    cleaned = re.sub(r"```(?:json)?|```", "", text or "").strip()
    start, end = cleaned.find("{"), cleaned.rfind("}")
    if start >= 0 and end > start:
        try:
            payload = json.loads(cleaned[start:end + 1])
        except ValueError:
            payload = None
        if isinstance(payload, dict) and isinstance(payload.get("keywords"),
                                                    (list, tuple)):
            return [str(k) for k in payload["keywords"]]
    return [k for k in re.findall(r'"([^"\n]{1,60})"', cleaned)
            if k.lower() != "keywords"]


def _top_up_keywords(meta: ImageMetadata, data: bytes, mime: str,
                     settings: MetadataSettings, api_key: str,
                     log=None) -> ImageMetadata:
    """Fill a slightly short keyword list up to the requested exact count, once.

    Small local models often answer with 40–45 of the 50 they were asked for.
    Only a modest shortfall is worth a cheap follow-up: a reply that ignored
    the count completely is better served by "Regenerate Selected" than by a
    second request that re-asks for nearly everything. A failed or empty
    top-up never discards the metadata that did arrive.
    """
    target = min(settings.keyword_count, ADOBE_KEYWORDS_MAX)
    missing = target - len(meta.keywords)
    if (not settings.exact_keyword_count or missing <= 0
            or missing > _KEYWORD_TOP_UP_MAX):
        return meta
    prompt = _keyword_top_up_prompt(settings, meta.keywords, missing)
    try:
        extra = _keywords_from_json(_call_ollama(data, mime, prompt, settings,
                                                 api_key))
    except Exception as exc:            # never lose a good first answer
        if log:
            log(f"  keyword top-up did not work ({exc}); keeping "
                f"{len(meta.keywords)} keyword(s)")
        return meta
    merged = sanitize_keywords(meta.keywords + extra, target)
    if log and len(merged) > len(meta.keywords):
        log(f"  keyword top-up added {len(merged) - len(meta.keywords)} "
            f"keyword(s) — now {len(merged)}/{target}")
    meta.keywords = merged
    return meta


def _ollama_get_json(base: str, api_key: str, path: str, payload=None,
                     label: str = "Ollama"):
    """GET/POST a small Ollama endpoint, returning (json, error_message)."""
    import requests

    url = f"{base}{path}"
    headers = _ollama_headers(api_key)
    try:
        if payload is None:
            resp = requests.get(url, headers=headers, timeout=OLLAMA_LOOKUP_TIMEOUT)
        else:
            resp = requests.post(url, headers=headers, json=payload,
                                 timeout=OLLAMA_LOOKUP_TIMEOUT)
    except requests.Timeout:
        return None, f"Ollama did not answer {path} within {OLLAMA_LOOKUP_TIMEOUT}s."
    except requests.ConnectionError:
        return None, f"Ollama did not answer at {base}."
    except requests.RequestException as exc:
        return None, f"{url}: {exc}"
    if resp.status_code != 200:
        return None, _classify_http(label, resp.status_code,
                                    _error_detail(resp) or resp.reason)
    try:
        return resp.json(), ""
    except ValueError as exc:
        return None, f"{url} sent an unexpected response: {exc}"


def _ollama_capabilities(base: str, api_key: str, model: str,
                         label: str = "Ollama"):
    """Capabilities for one locally installed model (``/api/show``).

    Returns ``(list | None, error)``; ``None`` means the server did not say.
    """
    payload, err = _ollama_get_json(base, api_key, "/api/show", {"model": model},
                                    label)
    if err:
        return None, err
    caps = (payload or {}).get("capabilities")
    return (list(caps) if isinstance(caps, (list, tuple)) else None), ""


def check_ollama(base_url: str, api_key: str = "", cloud: bool = False,
                 log=None, stopped=None) -> tuple[list[str], str]:
    """Connection + vision-model availability check for an Ollama mode.

    Returns ``(image_capable_models, message)``. Only models that advertise the
    ``vision`` capability are offered, because every request here attaches an
    image: the cloud (and recent local builds) include a ``capabilities`` array
    in ``/api/tags``, older local servers need a per-model ``/api/show``.
    ``message`` always explains the outcome, including unreachable servers,
    rejected cloud keys and accounts without a usable model. ``stopped`` is an
    optional callable that lets the UI abandon the per-model lookups while a
    check is still running.
    """
    try:
        import requests  # noqa: F401  (presence check; calls use _ollama_get_json)
    except ImportError as exc:
        raise missing_dependency("requests") from exc

    label = "Ollama Cloud" if cloud else "Local Ollama"
    if cloud and not (api_key or "").strip():
        return [], ("Ollama Cloud needs an API key — create one at "
                    "https://ollama.com/settings/keys and enter it here (or set "
                    "the OLLAMA_API_KEY environment variable).")
    try:
        base = ollama_base(base_url)
    except ProviderError as exc:
        return [], str(exc)

    data, err = _ollama_get_json(base, api_key, "/api/tags", label=label)
    if err:
        if cloud:
            return [], (f"Could not load the Ollama Cloud model list: {err} "
                        "Check the API key, your connection, and that your plan "
                        "includes cloud inference.")
        return [], (f"No Ollama server answered at {base} — start the Ollama app "
                    "(or run 'ollama serve') and try again. Local mode keeps "
                    "your images on this computer.")
    listed = (data or {}).get("models") or []
    if not listed:
        return [], (f"{label} is reachable but has no models to offer. Pull an "
                    "image-capable model first (for example 'ollama pull gemma4') "
                    "and run this check again.")

    vision: list[str] = []
    text_only: list[str] = []
    unknown: list[str] = []
    for entry in listed:
        if stopped is not None and stopped():
            return [], "Ollama check was stopped before every model was examined."
        if not isinstance(entry, dict):
            continue
        name = str(entry.get("name") or entry.get("model") or "").strip()
        if not name or name in vision or name in text_only or name in unknown:
            continue
        caps = entry.get("capabilities")
        if not isinstance(caps, (list, tuple)):
            caps, show_err = _ollama_capabilities(base, api_key, name, label)
            if show_err:
                unknown.append(name)
                if log:
                    log(f"↻ {name}: capability lookup failed ({show_err})")
                continue
            if caps is None:
                unknown.append(name)
                continue
        names = {str(c).lower() for c in (caps or [])}
        if "vision" in names:
            vision.append(name)
        elif caps:
            text_only.append(name)
        else:
            unknown.append(name)

    if vision:
        note = (f"✓ {label} reachable at {base} — {len(vision)} image-capable "
                "model(s) available.")
        if text_only:
            note += f" {len(text_only)} model(s) skipped (no image support)."
        if unknown:
            note += f" {len(unknown)} model(s) unconfirmed — type the name if one works."
        return vision, note
    note = (f"✗ {label} answered at {base}, but none of its {len(listed)} "
            "model(s) can analyse images. Install a vision model (for example "
            "'ollama pull gemma4'), or pick one that your account includes.")
    if unknown:
        note += (" Could not confirm capabilities for: " + ", ".join(unknown[:8]) +
                 " — you can still type such a model name in the Model field.")
    return [], note
